#!/usr/bin/env node
/**
 * Vendors Prism (MIT) into src/syntax/vendor/ — no global, no auto-highlighting.
 *
 *   npm i -D prismjs && node scripts/vendor-prism.mjs
 *
 * - prism-core.ts            createPrism(): a private Prism instance (`window.Prism`
 *                            is never read nor written, host-page code is never touched)
 * - languages.base.ts        grammars bundled in k3ui.js (common web languages)
 * - languages.extended.ts    every other grammar — shipped as dist/k3ui-syntax.js and
 *                            loaded on demand by <k3-codeblock>
 * - manifest.ts              ids, titles, aliases, tier
 *
 * Grammar files are wrapped as `function (Prism) { …original source… }` and ordered
 * from components.json (require / optional / modify).
 */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const PRISM = dirname(require.resolve('prismjs/package.json'));
const OUT = resolve(ROOT, 'src/syntax/vendor');
const { version } = JSON.parse(readFileSync(resolve(PRISM, 'package.json'), 'utf8'));
const { languages: meta } = JSON.parse(readFileSync(resolve(PRISM, 'components.json'), 'utf8'));

/** Bundled in k3ui.js — keep it small (bundle budget). */
const BASE = ['markup', 'css', 'clike', 'javascript', 'typescript', 'jsx', 'tsx', 'json'];

/** Loaded on demand (dist/k3ui-syntax.js). Dependencies are added automatically. */
const EXTENDED = [
  'php', 'scss', 'sass', 'sql', 'c', 'cpp', 'csharp', 'git', 'batch', 'autohotkey', 'asciidoc',
  'go', 'python', 'http', 'markdown', 'lua', 'mongodb', 'nginx', 'bash', 'powershell', 'yaml',
  'diff', 'docker', 'ini', 'toml', 'java', 'kotlin', 'rust', 'ruby', 'swift', 'graphql', 'regex',
];

/** Extra aliases people actually type in fences / attributes. */
const EXTRA_ALIASES = {
  markup: ['html', 'xml', 'svg', 'mathml', 'xhtml'],
  javascript: ['js', 'mjs', 'cjs'],
  typescript: ['ts', 'mts', 'cts'],
  jsx: ['react'],
  tsx: ['react-ts'],
  sql: ['sqlite', 'mysql', 'mariadb', 'postgres', 'postgresql', 'pgsql', 'tsql'],
  cpp: ['c++', 'cc', 'hpp', 'cxx'],
  csharp: ['c#', 'cs', 'dotnet'],
  c: ['h'],
  batch: ['bat', 'cmd'],
  autohotkey: ['ahk'],
  asciidoc: ['adoc'],
  go: ['golang'],
  python: ['py'],
  markdown: ['md'],
  mongodb: ['mongo'],
  bash: ['sh', 'shell', 'zsh'],
  powershell: ['ps1', 'pwsh'],
  yaml: ['yml'],
  docker: ['dockerfile'],
  kotlin: ['kt', 'kts'],
  rust: ['rs'],
  ruby: ['rb'],
  graphql: ['gql'],
  diff: ['patch'],
  nginx: ['nginxconf'],
};

const list = (v) => (v ? (Array.isArray(v) ? v : [v]) : []);

/** Dependency closure + load order (require ∪ optional ∪ modify, when selected). */
function order(ids, preloaded = new Set()) {
  const wanted = new Set();
  const visit = (id) => {
    if (wanted.has(id) || preloaded.has(id)) return;
    if (!meta[id]) throw new Error(`Unknown Prism language: ${id}`);
    wanted.add(id);
    list(meta[id].require).forEach(visit);
  };
  ids.forEach(visit);
  const all = new Set([...preloaded, ...wanted]);
  const deps = (id) =>
    [...list(meta[id].require), ...list(meta[id].optional), ...list(meta[id].modify)].filter(
      (d) => all.has(d) && !preloaded.has(d),
    );
  const out = [];
  const done = new Set();
  const visiting = new Set();
  const place = (id) => {
    if (done.has(id)) return;
    if (visiting.has(id)) throw new Error(`Cycle at ${id}`);
    visiting.add(id);
    deps(id).forEach(place);
    visiting.delete(id);
    done.add(id);
    out.push(id);
  };
  [...wanted].sort().forEach(place);
  return out;
}

const header = (what) =>
  `// @ts-nocheck\n/* eslint-disable */\n/*\n * ${what}\n * Generated by scripts/vendor-prism.mjs from prismjs@${version} — do not edit.\n * Prism — MIT License, Copyright (c) 2012 Lea Verou (see PRISM-LICENSE.txt).\n */\n`;

function grammarFn(id) {
  const src = readFileSync(resolve(PRISM, `components/prism-${id}.js`), 'utf8').trim();
  const name = `lang_${id.replace(/[^a-z0-9]/gi, '_')}`;
  return { name, code: `function ${name}(Prism) {\n${src}\n}\n` };
}

function writeLanguages(file, exportName, ids, what) {
  const fns = ids.map(grammarFn);
  const body =
    header(what) +
    fns.map((f) => f.code).join('\n') +
    `\n/** [id, register] in load order. */\nexport const ${exportName} = [\n` +
    ids.map((id, i) => `  [${JSON.stringify(id)}, ${fns[i].name}],`).join('\n') +
    `\n];\n`;
  writeFileSync(resolve(OUT, file), body);
}

/* ── core ─────────────────────────────────────────────────────────────── */
let core = readFileSync(resolve(PRISM, 'components/prism-core.js'), 'utf8');
const selfDecl = /var _self = \(typeof window !== 'undefined'\)[\s\S]*?;\n/;
if (!selfDecl.test(core)) throw new Error('prism-core: _self declaration not found');
/* A private, empty "global": no window.Prism read/write, no DOMContentLoaded
   auto-highlighting, no worker message handler — the factory just returns Prism. */
core = core.replace(selfDecl, 'var _self = {};\n');
const tail = core.indexOf("if (typeof module !== 'undefined' && module.exports)");
if (tail < 0) throw new Error('prism-core: module export block not found');
core = core.slice(0, tail).trimEnd();
core = core.replace(/^\/\/\/ <reference[^\n]*\n/m, '');

mkdirSync(OUT, { recursive: true });
writeFileSync(
  resolve(OUT, 'prism-core.ts'),
  header('Prism core — private instance factory') +
    `\n/** A fresh, private Prism (never touches window.Prism or the host page). */\nexport function createPrism() {\n${core}\n\treturn Prism;\n}\n`,
);

/* ── languages ────────────────────────────────────────────────────────── */
const baseOrder = order(BASE);
const extendedOrder = order(EXTENDED, new Set(baseOrder));
writeLanguages('languages.base.ts', 'BASE_LANGUAGES', baseOrder, 'Grammars bundled in k3ui.js');
writeLanguages(
  'languages.extended.ts',
  'LANGUAGES',
  extendedOrder,
  'Grammars loaded on demand (dist/k3ui-syntax.js)',
);

/* ── manifest ─────────────────────────────────────────────────────────── */
const manifest = {};
for (const [tier, ids] of [
  ['base', baseOrder],
  ['extended', extendedOrder],
]) {
  for (const id of ids) {
    const aliases = [...new Set([...list(meta[id].alias), ...(EXTRA_ALIASES[id] ?? [])])].filter((a) => a !== id);
    manifest[id] = { title: meta[id].title, aliases, tier };
  }
}
writeFileSync(
  resolve(OUT, 'manifest.ts'),
  header('Language manifest') +
    `\nexport interface SyntaxLanguageInfo {\n  title: string;\n  aliases: readonly string[];\n  tier: 'base' | 'extended';\n}\n\nexport const PRISM_VERSION = ${JSON.stringify(version)};\n\nexport const LANGUAGE_MANIFEST: Readonly<Record<string, SyntaxLanguageInfo>> = ${JSON.stringify(manifest, null, 2)};\n`,
);
copyFileSync(resolve(PRISM, 'LICENSE'), resolve(OUT, 'PRISM-LICENSE.txt'));

console.log(
  `prismjs@${version} → base: ${baseOrder.join(', ')}\n  extended (${extendedOrder.length}): ${extendedOrder.join(', ')}`,
);
